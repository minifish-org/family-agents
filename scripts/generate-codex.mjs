import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";

// Keep only protocol types used by this adapter and their dependencies.
const roots = [
  "InitializeParams", "InitializeResponse",
  ...[
    "ModelListParams", "ModelListResponse", "ThreadStartParams", "ThreadStartResponse",
    "ThreadResumeParams", "ThreadResumeResponse", "ThreadForkParams", "ThreadForkResponse", "TurnStartParams", "TurnStartResponse",
    "ThreadUnsubscribeParams", "ThreadUnsubscribeResponse", "ThreadLoadedListParams", "ThreadLoadedListResponse",
    "TurnInterruptParams", "TurnInterruptResponse", "ThreadItem", "Turn",
    "GetAccountParams", "GetAccountResponse", "LoginAccountParams", "LoginAccountResponse",
    "LogoutAccountResponse", "CancelLoginAccountParams", "CancelLoginAccountResponse",
    "ItemCompletedNotification", "ItemStartedNotification", "AgentMessageDeltaNotification",
    "TurnCompletedNotification", "ErrorNotification", "DynamicToolCallParams", "DynamicToolCallResponse",
    "AccountUpdatedNotification", "AccountLoginCompletedNotification",
    "CommandExecutionRequestApprovalResponse", "FileChangeRequestApprovalResponse",
    "PermissionsRequestApprovalResponse",
  ].map((name) => `v2/${name}`),
];
const binary = process.env.CODEX_BIN || "codex";
const temporary = mkdtempSync(join(tmpdir(), "family-codex-types-"));
const output = resolve("server/generated/codex");
try {
  const version = execFileSync(binary, ["--version"], { encoding: "utf8" }).trim();
  execFileSync(binary, ["app-server", "generate-ts", "--experimental", "--out", temporary], { stdio: "inherit" });
  rmSync(output, { recursive: true, force: true });
  const copied = new Set();
  function copy(name) {
    const source = resolve(temporary, `${name}.ts`);
    if (copied.has(source)) return;
    copied.add(source);
    let content = readFileSync(source, "utf8");
    content = content.replace(/from "(\.[^"]+)"/g, (_, relative) => {
      copy(resolve(dirname(source), relative).slice(temporary.length + 1));
      return `from "${relative}.js"`;
    });
    const target = resolve(output, `${name}.ts`);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  roots.forEach(copy);
  writeFileSync(join(output, "VERSION"), `${version}\nGenerated by npm run codex:generate with experimental dynamic tools.\n`);
  console.log(`Generated ${copied.size} protocol files from ${version}.`);
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
